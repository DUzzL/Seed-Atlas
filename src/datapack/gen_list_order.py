#!/usr/bin/env python3
"""Writes dplistorder.h: the game's order of the vanilla overworld biome list.

The overworld's biome parameter list is defined in the game's code
(OverworldBiomeBuilder), not in its data pack. The engine has the entries as
the leaves of the game's search tree (seedatlas-engine/tables/btree21wd.h), in
the order of that tree. From 26.3 the game builds the tree with another
number of children per node, and from 26.2 it has one entry more (Sulfur
Caves), so the tree of the engine no longer is the game's; building the
game's tree needs the entries in list order. This script finds, for every
entry of an official biome_parameters report, the leaf of the engine's table
with the same parameters, and writes the leaf numbers in report order. The
header holds nothing but these numbers.

Usage:
  gen_list_order.py <seedatlas-engine/tables/btree21wd.h> \\
      <reports/biome_parameters/minecraft/overworld.json of 1.21.5 .. 26.1> \\
      [<report of 26.2 or 26.3> ...] > dplistorder.h

The first report must be a list without Sulfur Caves (1.21.5 to 26.1.2 have
the same list); further reports are checked to be that list with the Sulfur
Caves entry inserted at the index the header gives (biome names may differ:
26.3 relabels some Plains entries as Dappled Forest).

The reports come from the game's data generator (java
-DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports); no game
data is part of the repository.
"""

import json
import re
import struct
import sys

KEYS = ["temperature", "humidity", "continentalness", "erosion", "depth", "weirdness"]


def quantize(v):
    # Climate.quantizeCoord(): (long) (value * 10000.0F), in float
    f = struct.unpack("f", struct.pack("f", v))[0]
    f = struct.unpack("f", struct.pack("f", f * 10000.0))[0]
    return int(f)


def box_of(entry):
    p = entry["parameters"]
    out = []
    for k in KEYS:
        v = p[k]
        if not isinstance(v, list):
            v = [v, v]
        out.append((quantize(v[0]), quantize(v[1])))
    if p.get("offset", 0) != 0:
        raise SystemExit("an entry with an offset")
    return tuple(out)


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    # the table without its comments
    src = re.sub(r"//[^\n]*", "", open(sys.argv[1]).read())
    params = [(int(a), int(b)) for a, b in
              re.findall(r"\{\s*(-?\d+),\s*(-?\d+)\}", src.split("_param[][2] =")[1].split("};")[0])]
    nodes = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]+)", src.split("_nodes[] =")[1].split("};")[0])]
    leaf = {}
    for i, n in enumerate(nodes):
        if (n >> 56) & 0xFF != 0xFF:
            continue
        box = tuple(params[(n >> (8 * d)) & 0xFF] for d in range(6))
        if box in leaf:
            raise SystemExit("two leaves with the same parameters")
        leaf[box] = i

    base = json.load(open(sys.argv[2]))["biomes"]
    order = []
    for e in base:
        box = box_of(e)
        if box not in leaf:
            raise SystemExit("an entry of the report is not in the table")
        order.append(leaf[box])
    if len(set(order)) != len(leaf) or len(order) != len(leaf):
        raise SystemExit("the report and the table do not have the same entries")

    sulfur = None
    for path in sys.argv[3:]:
        more = json.load(open(path))["biomes"]
        idx = [i for i, e in enumerate(more) if e["biome"] == "minecraft:sulfur_caves"]
        if len(idx) != 1 or len(more) != len(base) + 1:
            raise SystemExit("%s: not the list with one Sulfur Caves entry" % path)
        if sulfur is not None and idx[0] != sulfur:
            raise SystemExit("%s: Sulfur Caves at another index" % path)
        sulfur = idx[0]
        rest = more[:sulfur] + more[sulfur + 1:]
        if [box_of(e) for e in rest] != [box_of(e) for e in base]:
            raise SystemExit("%s: the other entries differ" % path)
    if sulfur is None:
        raise SystemExit("give a report of 26.2 or later as well (index of Sulfur Caves)")

    out = []
    out.append("// Generated by gen_list_order.py from the official biome_parameters reports")
    out.append("// of the game, do not edit. The vanilla overworld biome list of 1.21.5 to")
    out.append("// 26.3 in the game's order, as node numbers of the leaves of the engine's")
    out.append("// table btree21wd (seedatlas-engine/tables/btree21wd.h). From 26.2 the game")
    out.append("// inserts the Sulfur Caves entry at index DP_ORDER_SULFUR of the list.")
    out.append("")
    out.append("#ifndef DPLISTORDER_H")
    out.append("#define DPLISTORDER_H")
    out.append("")
    out.append("#include <cstdint>")
    out.append("")
    out.append("enum { DP_ORDER_SULFUR = %d };" % sulfur)
    out.append("")
    out.append("static const uint16_t dp_order_btree21wd[%d] =" % len(order))
    out.append("{")
    for i in range(0, len(order), 16):
        out.append("    " + ", ".join("%d" % v for v in order[i:i + 16]) + ",")
    out.append("};")
    out.append("")
    out.append("#endif // DPLISTORDER_H")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
