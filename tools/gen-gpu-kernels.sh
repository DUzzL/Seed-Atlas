#!/bin/sh
# Regenerates the GPU kernels from src/gpufilter.comp, one variant for each
# value of NOCT (the most octaves per octave noise of a test set):
#   src/gpufilter_spirv.inc  SPIR-V for Vulkan (Windows, Linux)
#   src/gpufilter_msl.inc    Metal Shading Language (macOS)
# Needs glslangValidator and spirv-cross (Debian/Ubuntu: glslang-tools spirv-cross).
set -eu
VARIANTS="2 3 4 9"   # the octave counts of the 1.18+ climate noises

cd "$(dirname "$0")/../src"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

header="// Generated by tools/gen-gpu-kernels.sh from gpufilter.comp, do not edit."
echo "$header" > "$tmp/spirv.inc"
echo "$header" > "$tmp/msl.inc"
for n in $VARIANTS; do
    glslangValidator -V --target-env vulkan1.1 -DNOCT=$n -o "$tmp/k$n.spv" gpufilter.comp >/dev/null
    # Metal: the permutations as bytes (see PERM_BYTES in gpufilter.comp)
    glslangValidator -V --target-env vulkan1.1 -DNOCT=$n -DPERM_BYTES -o "$tmp/m$n.spv" gpufilter.comp >/dev/null
    spirv-cross "$tmp/m$n.spv" --msl --msl-version 20300 --msl-decoration-binding \
        --rename-entry-point main climateFilter comp --output "$tmp/k$n.metal"
    {
        echo "static const uint32_t g_spirv_$n[] = {"
        od -An -v -tx4 "$tmp/k$n.spv" | tr -s ' \n' '\n\n' | sed '/^$/d; s/^/0x/; s/$/,/'
        echo "};"
    } >> "$tmp/spirv.inc"
    {
        echo "static const char g_msl_$n[] = R\"MSL("
        cat "$tmp/k$n.metal"
        echo ")MSL\";"
    } >> "$tmp/msl.inc"
done
{
    echo "static const GpuSpirvKernel g_spirv_kernels[] = {"
    for n in $VARIANTS; do echo "    { $n, g_spirv_$n, sizeof(g_spirv_$n) },"; done
    echo "};"
} >> "$tmp/spirv.inc"
{
    echo "static const GpuMslKernel g_msl_kernels[] = {"
    for n in $VARIANTS; do echo "    { $n, g_msl_$n },"; done
    echo "};"
} >> "$tmp/msl.inc"
cp "$tmp/spirv.inc" gpufilter_spirv.inc
cp "$tmp/msl.inc" gpufilter_msl.inc
echo "generated gpufilter_spirv.inc and gpufilter_msl.inc (variants: $VARIANTS)"
